// FT232H 数据缓冲FIFO（同步FIFO，wrclk与rdclk同源）
//260826    v1.0.0   初始版本

module ft_buf (
    input  [7:0] data,      //写数据
    input        rdclk,     //读时钟
    input        rdreq,     //读请求
    input        wrclk,     //写时钟
    input        wrreq,     //写请求
    output logic [7:0] q,   //读数据
    output logic       rdempty, //读空
    output logic [11:0] rdusedw, //读侧数据量
    output logic       wrfull,  //写满
    output logic [11:0] wrusedw  //写侧数据量
);

/////////////////////////////////////////////////////////////////////////////////////////
////////////////////                 内部信号                /////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////
localparam DEPTH = 4096; //FIFO深度

logic [7:0]  mem [0:DEPTH-1]; //存储体
logic [11:0] wr_ptr;          //写指针
logic [11:0] rd_ptr;          //读指针

/////////////////////////////////////////////////////////////////////////////////////////
////////////////////                初始化                  /////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////
initial begin
    wr_ptr = 12'd0;
    rd_ptr = 12'd0;
    q      = 8'd0;
end

/////////////////////////////////////////////////////////////////////////////////////////
////////////////////                 写操作                  /////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////
always@(posedge wrclk)begin
    if(wrreq && !wrfull)begin
        mem[wr_ptr] <= data;
        wr_ptr      <= wr_ptr + 1'b1;
    end
end

/////////////////////////////////////////////////////////////////////////////////////////
////////////////////                 读操作                  /////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////
always@(posedge rdclk)begin
    if(rdreq && !rdempty)begin
        q      <= mem[rd_ptr];
        rd_ptr <= rd_ptr + 1'b1;
    end
end

/////////////////////////////////////////////////////////////////////////////////////////
////////////////////              状态与数据量输出             /////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////
assign wrusedw = wr_ptr - rd_ptr;
assign rdusedw = wr_ptr - rd_ptr;
assign wrfull  = (wr_ptr + 1'b1 == rd_ptr);
assign rdempty = (wr_ptr == rd_ptr);

endmodule
