module audio_loop (
    input               i_clk,          //系统时钟 25MHz
    input               i_rst_n,        //系统复位，低有效

    //I2C接口
    inout               io_i2c_sdat,    //I2C数据
    output              o_i2c_sclk,     //I2C时钟

    //音频接口
    inout               io_aud_adclrck, //ADC左右声道时钟
    input               i_aud_adcdat,   //ADC数据
    output              o_aud_daclrck,  //DAC左右声道时钟
    output              o_aud_dacdat,   //DAC数据
    inout               io_aud_bclk     //音频位时钟
);

/////////////////////////////////////////////////////////////////////////////////////////
////////////////////                 内部信号                /////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////
logic        clk_12_8;   //12.288MHz音频时钟

assign o_aud_daclrck = io_aud_adclrck;

/////////////////////////////////////////////////////////////////////////////////////////
////////////////////               audio_pll例化             /////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////
audio_pll audio_pll_m0(
    .clk_in1                    (i_clk                      ),
    .clk_out1                   (clk_12_8                   )
);

/////////////////////////////////////////////////////////////////////////////////////////
////////////////////              i2c_init_dev例化           /////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////
i2c_init_dev i2c_init_dev_m0(
    .i_clk                      (i_clk                      ),
    .i_rst_n                    (i_rst_n                    ),
    .o_init_done                (                           ),
    .o_i2c_sclk                 (o_i2c_sclk                 ),
    .io_i2c_sdat                (io_i2c_sdat                )
);

/////////////////////////////////////////////////////////////////////////////////////////
////////////////////             audio_dac_fifo例化          /////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////
audio_dac_fifo audio_dac_fifo_m0(
    .i_data                     (16'd0                      ),
    .i_wr                       (1'b0                       ),
    .i_wr_clk                   (i_clk                      ),
    .o_data                     (                           ),
    .i_rd                       (1'b0                       ),
    .o_full                     (                           ),
    .o_empty                    (                           ),

    .i_aud_data                 (i_aud_adcdat               ),
    .o_aud_bck                  (io_aud_bclk                ),
    .o_aud_data                 (o_aud_dacdat               ),
    .o_aud_lrck                 (io_aud_adclrck             ),
    .o_aud_xck                  (                           ),

    .i_clk                      (clk_12_8                   ),
    .o_wr                       (                           ),
    .i_rst_n                    (i_rst_n                    )
);

endmodule
